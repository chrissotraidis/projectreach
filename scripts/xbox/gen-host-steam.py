#!/usr/bin/env python3
"""Generate HaloPad host copies of upstream's Steam Workshop and MCC hashing
host code (OpenCE builds after 359; port/android/host).

Upstream's Android host maps guest memory at host address 0, so its host
functions turn a guest address into a pointer with a plain cast. HaloPad's
guest memory is one reservation at xg_base (port/xbox/xg_host.h), so these
copies convert through GP(), which keeps a guest NULL a host NULL.

One other change: steam_downloads.c moves a finished download into mcc_maps
through upstream's posix_mcc_share_publish, which is atomic only on Linux
(renameat2) and refuses elsewhere, so on Apple platforms every Workshop
install failed at its last step ("The item could not be put in
mcc_maps/<id>"). The copy calls xg_mcc_share_publish (port/xbox/
xg_steam_host.m) instead: the same path checks, then Darwin's RENAME_EXCL,
as xg_posix.c already does for the game's own calls.

For the Apple TV's web page (port/xbox/xg_admin.m), port/xbox/
xg_steam_admin.inc is appended to the steam_downloads.c copy: it starts a
Steam sign-in with a name and password the page delivers, through the same
fields the game's own text boxes fill. A sign-in begun there is not
cancelled because the game's Steam screen is closed.

Each substitution is counted: if upstream moves or adds one, generation
fails instead of producing a host that misreads guest memory.

Also writes xg_steam_names.h, which renames the guest's imports (the
host_steam_*, host_mcc_hash_* and host_sha256_* lines of upstream's
port/android/host_imports.list) to HaloPad's xh_host_* names.

Usage: gen-host-steam.py <engine checkout> <out folder>
"""
import pathlib
import re
import sys

IMPORT = re.compile(r'^(host_(?:steam|mcc_hash|sha256)_[a-z0-9_]+)\s*$')

# steam_downloads.c: one macro carries every guest address of its host_steam_* functions.
STEAM_MACRO = '#define GUEST_POINTER(address) ((void *)(uintptr_t)(address))'
STEAM_REPLACEMENT = '#define GUEST_POINTER(address) GP(address) /* HaloPad: guest memory at xg_base */'

# steam_downloads.c: the one call that publishes a finished download.
PUBLISH_CALL = 'return posix_mcc_share_publish(from, to);'
PUBLISH_CALL_DARWIN = 'return xg_mcc_share_publish(from, to); /* HaloPad: Darwin RENAME_EXCL */'

# steam_downloads.c: a sign-in begun from the web page (xg_steam_admin.inc) is
# not cancelled because the game's Steam screen is closed.
SIGN_IN_CANCEL = 'cancelled = steam.cancel_sign_in || !steam.open;'
SIGN_IN_CANCEL_ADMIN = 'cancelled = steam.cancel_sign_in || (!steam.open && !xg_admin_sign_in_open);'
ADMIN_INCLUDE = pathlib.Path(__file__).resolve().parents[2] / 'port/xbox/xg_steam_admin.inc'

# host_mcc_hash.c: the guest addresses its six entry functions cast to pointers.
HASH_ADDRESSES = re.compile(
    r'\(uintptr_t\)(request_address|result_address|path_address|digest_address|size_address'
    r'|request->data_root|request->paths\[type\])(?![A-Za-z0-9_])')
HASH_EXPECTED = 8


def fail(message):
    sys.exit('gen-host-steam: ' + message)


def steam_downloads(source):
    """HaloPad's copy of upstream's steam_downloads.c."""
    if source.count(STEAM_MACRO) != 1:
        fail('steam_downloads.c no longer has exactly one GUEST_POINTER definition')
    if source.count('(uintptr_t)') != 1:
        fail('steam_downloads.c converts guest addresses outside GUEST_POINTER')
    if source.count(PUBLISH_CALL) != 1:
        fail('steam_downloads.c no longer publishes downloads in exactly one place')
    if source.count(SIGN_IN_CANCEL) != 1:
        fail('steam_downloads.c no longer cancels a sign-in in exactly one place')
    source = (source.replace(STEAM_MACRO, STEAM_REPLACEMENT).replace(PUBLISH_CALL, PUBLISH_CALL_DARWIN)
              .replace(SIGN_IN_CANCEL, SIGN_IN_CANCEL_ADMIN))
    return ('/* generated by scripts/xbox/gen-host-steam.py from port/android/host/steam_downloads.c */\n'
            '#include "xg_host.h"\n'
            'int xg_mcc_share_publish(const char *from, const char *to);\n'
            '/* HaloPad: set while the web page signs in (xg_steam_admin.inc) */\n'
            'static int xg_admin_sign_in_open;\n'
            '#line 1 "steam_downloads.c"\n' + source +
            '#line 1 "xg_steam_admin.inc"\n' + ADMIN_INCLUDE.read_text())


def mcc_hash(source):
    """HaloPad's copy of upstream's host_mcc_hash.c."""
    source, count = HASH_ADDRESSES.subn(r'(uintptr_t)GP(\1)', source)
    if count != HASH_EXPECTED:
        fail('host_mcc_hash.c has %d guest address casts, expected %d' % (count, HASH_EXPECTED))
    return ('/* generated by scripts/xbox/gen-host-steam.py from port/android/host/host_mcc_hash.c */\n'
            '#include "xg_host.h"\n#line 1 "host_mcc_hash.c"\n' + source)


def names_header(imports_list):
    names = [m.group(1) for line in imports_list.splitlines() if (m := IMPORT.match(line))]
    if not names:
        fail('no Steam or hashing imports in host_imports.list')
    header = ['/* generated by scripts/xbox/gen-host-steam.py: upstream host names -> HaloPad imports */',
              '#ifndef XG_STEAM_NAMES_H', '#define XG_STEAM_NAMES_H']
    header += ['#define %s xh_%s' % (name, name) for name in names]
    header += ['#endif', '']
    return '\n'.join(header), len(names)


def generate(engine, out):
    host = engine / 'port/android/host'
    header, count = names_header((engine / 'port/android/host_imports.list').read_text())
    (out / 'xg_steam_names.h').write_text(header)
    (out / 'xg_steam_downloads.c').write_text(steam_downloads((host / 'steam_downloads.c').read_text()))
    (out / 'xg_mcc_hash.c').write_text(mcc_hash((host / 'host_mcc_hash.c').read_text()))
    print('Steam host: %d imports renamed' % count)


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    generate(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
